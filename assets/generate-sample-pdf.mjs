/**
 * 生成 demo 用的最小合法 PDF（单页，含 xref 偏移计算）。
 * 仅本任务一次性使用：node scripts 生效后本文件可留在 scripts/ 供复现。
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const lines = [
  ["F1", 24, 720, "local-notes sample PDF"],
  ["F1", 12, 690, "This tiny file exists so the demo has a PDF to embed."],
  ["F1", 12, 672, "It is generated by a ~30-line script (see demo/assets/),"],
  ["F1", 12, 654, "so the repository stays free of binary bloat."],
  ["F1", 14, 610, "What this demonstrates"],
  ["F1", 12, 588, "- <PdfViewer src=\"/vault/assets/sample.pdf\" />"],
  ["F1", 12, 570, "- auto-embedded markdown links pointing at .pdf files"],
  ["F1", 12, 552, "- Obsidian-style ![[sample.pdf]] embeds"],
  ["F1", 12, 522, "Edit this text, re-run the script, refresh the page."],
];

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
const content = lines
  .map(([f, size, y, text]) => `BT /${f} ${size} Tf 72 ${y} Td (${esc(text)}) Tj ET`)
  .join("\n");

const objects = [
  "<< /Type /Catalog /Pages 2 0 R >>",
  "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
  "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
  "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  `<< /Length ${Buffer.byteLength(content)} >>\nstream\n${content}\nendstream`,
];

let pdf = "%PDF-1.4\n";
const offsets = [0];
objects.forEach((body, i) => {
  offsets.push(Buffer.byteLength(pdf));
  pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
});
const xrefStart = Buffer.byteLength(pdf);
pdf += `xref\n0 ${objects.length + 1}\n`;
pdf += "0000000000 65535 f \n";
for (let i = 1; i <= objects.length; i++) pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

const out = fileURLToPath(new URL("../assets/sample.pdf", import.meta.url));
writeFileSync(out, pdf, "latin1");
console.log(`written ${out} (${Buffer.byteLength(pdf)} bytes)`);
